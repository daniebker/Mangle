int font_draw(uint8_t* buf, int w, int h, int x, int y, int scale, const char* s, uint8_t color)
{
	int x0 = x;
	for (; *s; s++, x += FONT_W * scale) {
		unsigned c = (unsigned char) *s;
		if (c < 32 || c > 126)
			c = '?';
		const unsigned char* g = font_data[c - 32];
		for (int r = 0; r < FONT_H; r++)
			for (int b = 0; b < FONT_W; b++) {
				if (!(g[r] & (0x80 >> b)))
					continue;
				for (int dy = 0; dy < scale; dy++) {
					int py = y + r * scale + dy;
					if (py < 0 || py >= h)
						continue;
					for (int dx = 0; dx < scale; dx++) {
						int px = x + b * scale + dx;
						if (px >= 0 && px < w)
							buf[(size_t) py * w + px] = color;
					}
				}
			}
	}
	return x - x0;
}
