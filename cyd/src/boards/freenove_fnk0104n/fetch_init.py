# PlatformIO pre-build script for the Freenove FNK0104N.
#
# The ST77922 panel needs its maker's initialisation sequence (power, gamma
# and gate timing registers, specific to this glass). Freenove publishes it
# under CC BY-NC-SA 3.0, which can't be mixed into Mangle's AGPL source, so,
# like FBInk for the Kindle, it is fetched when you build rather than stored
# in this repository: this script downloads Freenove's library at a pinned
# commit, takes only the register table out of ST77922.cpp, and writes it as
# a header in the build folder. (Credit: Freenove, Freenove_ESP32_S3_Display.)
#
# Also runnable on its own: python fetch_init.py OUT_DIR
import io
import os
import re
import sys
import urllib.request
import zipfile

COMMIT = "90004f874ed567b3c09d534d021172cb716e61a1"
URL = ("https://raw.githubusercontent.com/Freenove/Freenove_ESP32_S3_Display/"
       f"{COMMIT}/Libraries/FNK0104N/TFT_eSPI_v2.5.43.zip")
ENTRY = re.compile(r"\{\s*0x([0-9A-Fa-f]{2})\s*,\s*\(uint8_t\s*\[\]\)\s*\{([^}]*)\}\s*,\s*(\d+)\s*,\s*(\d+)\s*\}")


def table_from_source(src: str):
    """[(cmd, [bytes], delay_ms)] from the st77922_lcd_init[] array."""
    start = src.index("st77922_lcd_init[]")
    body = src[start:src.index("};", start)]
    out = []
    for m in ENTRY.finditer(body):
        cmd = int(m.group(1), 16)
        data = [int(v, 16) for v in re.findall(r"0x([0-9A-Fa-f]{1,2})", m.group(2))]
        n = int(m.group(3))
        out.append((cmd, data[:n], int(m.group(4))))
    if len(out) < 20:
        raise ValueError(f"only {len(out)} init commands found")
    return out


def header(table) -> str:
    lines = [
        "// Generated by fetch_init.py from Freenove_ESP32_S3_Display",
        f"// (commit {COMMIT}, ST77922.cpp), CC BY-NC-SA 3.0. Not part of Mangle's source.",
        "#pragma once",
        "#include <stdint.h>",
        "typedef struct { uint8_t cmd, len; uint8_t data[16]; uint16_t delay_ms; } St77922Init;",
        "static const St77922Init st77922_init[] = {",
    ]
    for cmd, data, delay in table:
        bytes_ = ", ".join(f"0x{b:02X}" for b in data) or "0"
        lines.append(f"\t{{ 0x{cmd:02X}, {len(data)}, {{ {bytes_} }}, {delay} }},")
    lines.append("};")
    return "\n".join(lines) + "\n"


def generate(out_dir: str) -> str:
    path = os.path.join(out_dir, "st77922_init.h")
    if os.path.exists(path):
        return path
    os.makedirs(out_dir, exist_ok=True)
    cache = os.path.join(out_dir, f"freenove-{COMMIT[:12]}.zip")
    if not os.path.exists(cache):
        print(f"Fetching the ST77922 init sequence from Freenove ({COMMIT[:12]})")
        with urllib.request.urlopen(URL, timeout=120) as r:
            data = r.read()
        with open(cache, "wb") as f:
            f.write(data)
    with zipfile.ZipFile(cache) as z:
        name = next(n for n in z.namelist() if n.endswith("/ST77922.cpp"))
        src = z.read(name).decode("utf-8", "replace")
    with open(path, "w") as f:
        f.write(header(table_from_source(src)))
    return path


if __name__ == "__main__" and "env" not in globals():
    print(generate(sys.argv[1] if len(sys.argv) > 1 else "."))
else:
    Import("env")  # noqa: F821  (SCons)
    out = os.path.join(env.subst("$PROJECT_BUILD_DIR"), env.subst("$PIOENV"), "generated")  # noqa: F821
    generate(out)
    env.Append(CPPPATH=[out])  # noqa: F821
